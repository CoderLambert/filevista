function inferMime(filename) {
  return MIME_MAP[extname(filename).toLowerCase()] ?? "application/octet-stream";
}

function listDemoFiles() {
  let entries;
  try {
    entries = readdirSync(DEMO_DIR);
  } catch (err) {
    if (err.code === "ENOENT") {
      console.warn(`[sync-demos] ${DEMO_DIR} does not exist — emitting empty list`);
      return [];
    }
    throw err;
  }
  return entries
    .filter((name) => !name.startsWith(".")) // skip .gitkeep, .DS_Store, etc.
    .map((name) => {
      const full = join(DEMO_DIR, name);
      const stat = statSync(full);
      if (!stat.isFile()) return null;
      return {
        name,
        path: `/demo/${name}`,
        type: inferMime(name),
        size: stat.size,
      };
    })
    .filter(Boolean)
    .sort((a, b) => a.name.localeCompare(b.name, "zh-CN"));
}

function render(entries) {
  const header = `// AUTO-GENERATED by apps/playground/scripts/sync-demos.mjs
// Do not edit — drop files into apps/playground/public/demo/ and re-run
// \`pnpm run sync:demos\` (or just \`pnpm run dev\` / \`pnpm run build\`).

export interface DemoFileEntry {
  /** Original filename, e.g. "report.pdf" */
  name: string;
  /** URL path under public, e.g. "/demo/report.pdf" — pass to resolveAssetPath() */
  path: string;
  /** MIME type inferred from file extension */
  type: string;
  /** File size in bytes (informational) */
  size: number;
}

export const DEMO_FILE_ENTRIES: DemoFileEntry[] = ${JSON.stringify(entries, null, 2)};
`;
  return header;
}

function main() {
  const entries = listDemoFiles();
  mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
  writeFileSync(OUTPUT_FILE, render(entries), "utf8");
  console.log(
    `[sync-demos] wrote ${entries.length} entries → ${OUTPUT_FILE.replace(PLAYGROUND_DIR, "apps/playground")}`
  );
}

main();
