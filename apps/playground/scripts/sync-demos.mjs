// Auto-sync `public/demo/` → `src/lib/demos.generated.ts`.
//
// Run via `pnpm run sync:demos`, or implicitly chained from `dev` / `build`.
// Drop a file into `public/demo/`, restart, and the playground's "Load Demo"
// button picks it up — no edits to `demos.ts`.

import { readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PLAYGROUND_DIR = resolve(__dirname, "..");
const DEMO_DIR = join(PLAYGROUND_DIR, "public", "demo");
const OUTPUT_FILE = join(PLAYGROUND_DIR, "src", "lib", "demos.generated.ts");

// Extension → MIME map. Extend here when you drop in a new format.
